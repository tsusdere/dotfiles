local map = function(lhs, rhs, desc, mode)
  vim.keymap.set(mode or "n", lhs, rhs, { silent = true, desc = desc })
end

map("jk", "<Esc>", "Exit insert mode", "i")
map("<Esc>", "<cmd>nohlsearch<CR>", "Clear search highlighting")
map("+", "<C-a>", "Increment number")
map("-", "<C-x>", "Decrement number")
map("<C-a>", "ggVG", "Select all")
map("x", '"_x', "Delete character without yanking")
map("<leader>p", '"0p', "Paste last yank", { "n", "x" })
map("<leader>P", '"0P', "Paste last yank before cursor")
map("<leader>d", '"_d', "Delete without yanking", { "n", "x" })
map("<leader>c", '"_c', "Change without yanking", { "n", "x" })

map("te", "<cmd>tabnew<CR>", "New tab")
map("<Tab>", "<cmd>tabnext<CR>", "Next tab")
map("<S-Tab>", "<cmd>tabprevious<CR>", "Previous tab")
map("<leader>w", "<cmd>write<CR>", "Save file")
map("<leader>q", "<cmd>quit<CR>", "Close window")
map("<leader>qq", "<cmd>quitall<CR>", "Quit Neovim")
map("ss", "<cmd>split<CR>", "Horizontal split")
map("sv", "<cmd>vsplit<CR>", "Vertical split")
for key, direction in pairs({ h = "left", j = "down", k = "up", l = "right" }) do
  map("s" .. key, "<C-w>" .. key, "Move to " .. direction .. " window")
end

map("sf", function()
  require("oil").open_float(nil, { preview = {} })
end, "File explorer")
map("<leader>e", function()
  require("oil").open()
end, "File explorer")
map(";f", Snacks.picker.files, "Find files")
map(";r", Snacks.picker.grep, "Search project")
map(";;", Snacks.picker.resume, "Resume picker")
map("\\\\", Snacks.picker.buffers, "Buffers")
map(";e", Snacks.picker.diagnostics, "Diagnostics")
map(";n", Snacks.picker.notifications, "Notifications")
map(";g", Snacks.lazygit.open, "Lazygit")
map(";h", Snacks.picker.git_diff, "Git hunks")
map("<leader><space>", Snacks.picker.files, "Find files")
map("<leader>/", Snacks.picker.grep, "Search project")
map("<leader>ff", Snacks.picker.files, "Find files")
map("<leader>fb", Snacks.picker.buffers, "Buffers")
map("<leader>gg", Snacks.lazygit.open, "Lazygit")
map("<leader>bd", Snacks.bufdelete.delete, "Delete buffer")
map("<leader>cl", Snacks.picker.lsp_config, "Language server info")
map("<leader>cR", Snacks.rename.rename_file, "Rename file")
map("<leader>f", function()
  require("conform").format()
end, "Format code", { "n", "x" })
map("<leader>uf", "<cmd>ToggleFormatter<CR>", "Toggle format on save")
map("<leader>xx", "<cmd>Trouble diagnostics toggle<CR>", "Toggle diagnostics")
map("<leader>gb", function()
  require("gitsigns").blame_line()
end, "Blame line")
map("<leader>gh", function()
  require("gitsigns").stage_hunk()
end, "Stage hunk")
map("<leader>gd", function()
  require("mini.diff").toggle_overlay()
end, "Toggle diff overlay")
map("<leader>dv", "<cmd>CodeDiff<CR>", "Git diff explorer")
map("<leader>dh", "<cmd>CodeDiff history %<CR>", "File history")
map("[d", function()
  vim.diagnostic.jump({ count = -1, float = true })
end, "Previous diagnostic")
map("]d", function()
  vim.diagnostic.jump({ count = 1, float = true })
end, "Next diagnostic")
map("<leader>i", function()
  vim.lsp.inlay_hint.enable(not vim.lsp.inlay_hint.is_enabled({ bufnr = 0 }), { bufnr = 0 })
end, "Toggle inlay hints")
map("<leader>yf", function()
  vim.fn.setreg("+", vim.fn.expand("%:.") .. ":" .. vim.fn.line("."))
end, "Copy relative path and line")
map("<leader>yp", function()
  vim.fn.setreg("+", vim.fn.expand("%:p") .. ":" .. vim.fn.line("."))
end, "Copy absolute path and line")
